/* Amines site engine: data loading, the 3D conformer panel (species, conformer, atom labels, tap-to-measure)
   and the CO2 solubility panel (one chart; concentration, temperature, data type and literature source chosen beside it).
   index.html only supplies layout and CSS for the am-* class names. Needs 3Dmol.js and Chart.js loaded first.
   data/, xyz/ and svg/ are generated by a local script outside this repo: do not edit them by hand. */
'use strict';
const AM = (() => {
  const BASE = window.AM_BASE || './';
  let DATA = null;
  const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  const sub = (f) => esc(f).replace(/(\d+)/g, '<sub>$1</sub>');
  const SPECIES = { A: 'Amine', P: 'Protonated (AmH⁺)', C: 'Carbamate (AmCOO⁻)' };
  const SHORT = { A: 'Am', P: 'AmH⁺', C: 'AmCOO⁻' };
  const CLASSES = ['Primary', 'Secondary', 'Cyclic', 'Other'];
  async function load() {
    if (!DATA) DATA = await (await fetch(BASE + 'data/amines.json')).json();
    return DATA.amines;
  }
  const svg = (id) => BASE + 'svg/' + encodeURIComponent(id) + '.svg';
  const store = { get(k, d) { try { return localStorage.getItem(k) ?? d; } catch (e) { return d; } }, set(k, v) { try { localStorage.setItem(k, v); } catch (e) {} } };

  /* atom labels: numbered per element in file order (C1, C2, N1, O1, H1 ...) */
  const atomLabels = (atoms) => { const n = {}; return atoms.map((a) => { n[a.elem] = (n[a.elem] || 0) + 1; return a.elem + n[a.elem]; }); };

  /* ---------- 3D conformers: species, conformer, atom labels, tap-to-measure ---------- */
  function confPanel(el, a, T = {}) {
    const th = Object.assign({ bg: '#0B1422', pick: '#E2A93B', labelBg: '#FFFFFF', labelFg: '#16325C', compact: false }, T);
    const sps = Object.keys(a.conformers || {}).filter((k) => a.conformers[k].length);
    if (!sps.length) { el.innerHTML = '<div class="am-todo">3D conformers for this amine are being added.</div>'; return null; }
    let sp = sps[0], labels = store.get('am-labels', 'off');
    el.innerHTML = `
      <div class="am-ctrl">
        <span class="am-seg" role="group" aria-label="Species">${sps.map((k) => `<button data-s="${k}" aria-pressed="${k === sp}">${th.compact ? SHORT[k] : SPECIES[k]}</button>`).join('')}</span>
        <label class="am-lbl">Conformer <select class="am-sel" aria-label="Conformer"></select></label>
        <span class="am-seg am-labels" role="group" aria-label="Atom labels"><b>Labels</b>${[['off', 'Off'], ['heavy', 'C, N, O'], ['all', 'All']].map(([k, t]) => `<button data-l="${k}" aria-pressed="${k === labels}">${t}</button>`).join('')}</span>
        <button class="am-btn am-clear">Clear</button>
      </div>
      <div class="am-viewer"><div class="am-readout"></div></div>
      <p class="am-hint">Drag to rotate · pinch or scroll to zoom · tap 2 atoms for a distance, 3 for an angle.</p>`;
    const sel = el.querySelector('.am-sel'), ro = el.querySelector('.am-readout'), box = el.querySelector('.am-viewer');
    const v = $3Dmol.createViewer(box, { backgroundColor: th.bg, antialias: true });
    let atoms = [], names = [], picked = [];
    const fill = () => {
      sel.innerHTML = a.conformers[sp].map((c, i) => `<option value="${c.n}">#${c.n}${c.pop != null ? ` · ${(100 * c.pop).toFixed(c.pop < 0.01 ? 2 : 1)} %` : ''}${i === 0 ? ' · most populated' : ''}</option>`).join('');
    };
    const d3 = (p, q) => Math.hypot(p.x - q.x, p.y - q.y, p.z - q.z);
    const draw = () => {
      v.removeAllShapes(); v.removeAllLabels();
      v.setStyle({}, { stick: { radius: 0.14, colorscheme: 'Jmol' }, sphere: { scale: 0.26, colorscheme: 'Jmol' } });
      if (labels !== 'off') atoms.forEach((at, i) => {
        if (labels === 'heavy' && at.elem === 'H') return;
        v.addLabel(names[i], { position: { x: at.x, y: at.y, z: at.z }, inFront: true, fontSize: at.elem === 'H' ? 10 : 12, fontColor: th.labelFg,
          backgroundColor: th.labelBg, backgroundOpacity: 0.85, borderThickness: 0, alignment: 'center', showBackground: true });
      });
      const P = picked.map((i) => atoms[i]);
      P.forEach((p) => v.addSphere({ center: { x: p.x, y: p.y, z: p.z }, radius: 0.48, color: th.pick, opacity: 0.45 }));
      for (let k = 0; k + 1 < P.length; k++) v.addCylinder({ start: P[k], end: P[k + 1], radius: 0.035, color: th.pick, dashed: true, fromCap: 1, toCap: 1 });
      const nm = (p) => names[atoms.indexOf(p)];
      let txt = '';
      if (P.length === 1) txt = `<span>${nm(P[0])} selected · tap another atom</span>`;
      if (P.length >= 2) txt = `<span>${nm(P[0])}–${nm(P[1])} <b>${d3(P[0], P[1]).toFixed(3)} Å</b></span>`;
      if (P.length === 3) {
        const u = [P[0].x - P[1].x, P[0].y - P[1].y, P[0].z - P[1].z], w = [P[2].x - P[1].x, P[2].y - P[1].y, P[2].z - P[1].z];
        const ang = Math.acos(Math.max(-1, Math.min(1, (u[0] * w[0] + u[1] * w[1] + u[2] * w[2]) / (Math.hypot(...u) * Math.hypot(...w))))) * 180 / Math.PI;
        txt += `<span>${nm(P[1])}–${nm(P[2])} <b>${d3(P[1], P[2]).toFixed(3)} Å</b></span><span>∠ ${nm(P[0])}–${nm(P[1])}–${nm(P[2])} <b>${ang.toFixed(1)}°</b></span>`;
      }
      ro.innerHTML = txt; v.render();
    };
    const loadConf = async () => {
      const xyz = await (await fetch(`${BASE}xyz/${encodeURIComponent(a.id)}/${sp}_${sel.value}.xyz`)).text();
      v.clear(); picked = [];
      const m = v.addModel(xyz, 'xyz'); atoms = m.selectedAtoms({}); names = atomLabels(atoms);
      v.setClickable({}, true, (at) => {
        const i = atoms.indexOf(atoms.find((x) => x.index === at.index));
        if (picked.includes(i)) picked = picked.filter((x) => x !== i); else { if (picked.length === 3) picked = []; picked.push(i); }
        draw();
      });
      v.zoomTo(); v.zoom(1.15); draw();
    };
    el.querySelectorAll('[data-s]').forEach((b) => b.onclick = () => { sp = b.dataset.s; el.querySelectorAll('[data-s]').forEach((x) => x.setAttribute('aria-pressed', x === b)); fill(); loadConf(); });
    el.querySelectorAll('[data-l]').forEach((b) => b.onclick = () => { labels = b.dataset.l; store.set('am-labels', labels); el.querySelectorAll('[data-l]').forEach((x) => x.setAttribute('aria-pressed', x === b)); draw(); });
    sel.onchange = loadConf;
    el.querySelector('.am-clear').onclick = () => { picked = []; draw(); };
    fill(); loadConf();
    new ResizeObserver(() => v.resize()).observe(box);
    return { viewer: v, spin(on) { v.spin(on ? 'y' : false); } };
  }

  /* ---------- CO2 solubility: one chart; concentration, temperature, data type and source chosen beside it ---------- */
  // temperatures get clearly different colours (category palette by rank within the chosen concentration)
  const TCOL = ['#1f77b4', '#ff7f0e', '#2ca02c', '#d62728', '#9467bd', '#8c564b', '#e377c2', '#17becf', '#bcbd22', '#7f7f7f', '#000000', '#393b79'];
  // experimental sources get different marker shapes (filled), then the same shapes hollow
  const SHAPES = ['circle', 'triangle', 'rect', 'rectRot', 'rectRounded', 'star'];
  const shapeSVG = (k, hollow) => {
    const f = hollow ? 'none' : '#888', s = 'stroke="currentColor" stroke-width="1.4"';
    return `<svg class="am-shape" viewBox="0 0 16 16">${[
      `<circle cx="8" cy="8" r="5.2" fill="${f}" ${s}/>`, `<path d="M8 2.6l5.6 9.8H2.4z" fill="${f}" ${s}/>`, `<rect x="3" y="3" width="10" height="10" fill="${f}" ${s}/>`,
      `<path d="M8 2l6 6-6 6-6-6z" fill="${f}" ${s}/>`, `<rect x="3" y="3" width="10" height="10" rx="3" fill="${f}" ${s}/>`,
      `<path d="M8 1.8l1.8 4.1 4.4.4-3.3 2.9 1 4.3L8 11.3l-3.9 2.2 1-4.3L1.8 6.3l4.4-.4z" fill="${f}" ${s}/>`][k % SHAPES.length]}</svg>`;
  };
  const tColor = (i) => TCOL[i % TCOL.length];
  async function co2Panel(el, a, T = {}) {
    const th = Object.assign({ fg: '#16325C', grid: '#E3E8EF', edge: '#000', font: 'inherit', h: 420 }, T);
    if (!a.co2_points) { el.innerHTML = '<div class="am-todo">No CO₂ solubility data for this amine yet.</div>'; return; }
    el.innerHTML = '<p class="am-hint">Loading…</p>';
    const d = await (await fetch(`${BASE}data/co2/${encodeURIComponent(a.id)}.json`)).json();
    const SRC = d.sources && d.sources.length ? d.sources : [{ key: 'exp', label: 'Experiment' }];
    const G = d.groups;
    let gi = G.reduce((b, g, i) => (g.exp.length > G[b].exp.length ? i : b), 0);
    const on = { exp: true, model: true, pred: true }, sOn = new Set(SRC.map((s, i) => i));
    let tOn = null, chart = null;
    const tempsOf = (g) => [...new Set([...g.exp.map((e) => e[0]), ...Object.keys(g.curves).map(Number)])].sort((p, q) => p - q);
    el.innerHTML = `
      <div class="am-co2">
        <div class="am-plot"><h4 class="am-ptitle"></h4><div class="am-cv" style="height:${th.h}px"><canvas aria-label="CO2 partial pressure versus loading"></canvas></div></div>
        <aside class="am-side">
          <div class="am-group"><h5>Concentration</h5><div class="am-concs" role="radiogroup">${G.map((g, i) => `<label class="am-conc"><input type="radio" name="am-conc-${esc(a.id)}" value="${i}" ${i === gi ? 'checked' : ''}><span>${+g.m.toFixed(2)} mol/kg <small>${g.wt} wt % · ${g.exp.length} pts</small></span></label>`).join('')}</div></div>
          <div class="am-group"><h5>Temperature <button class="am-mini" data-all="1">all</button><button class="am-mini" data-all="0">none</button></h5><div class="am-temps"></div></div>
          <div class="am-group"><h5>Show</h5><div class="am-legend">${[['exp', 'Experiment'], ['model', 'eNRTL-RK model (regressed)'], ['pred', 'Predicted (QM + MD)']].map(([k, s]) => `<label><input type="checkbox" data-k="${k}" checked>${k === 'exp' ? shapeSVG(0) : `<svg class="am-key" viewBox="0 0 26 12"><line x1="1" y1="6" x2="25" y2="6" stroke="currentColor" stroke-width="2.4" ${k === 'model' ? 'stroke-dasharray="5 3"' : ''}/></svg>`}${s}</label>`).join('')}</div></div>
          <div class="am-group"><h5>Experimental data from</h5><div class="am-srcs"></div></div>
        </aside>
      </div>
      <p class="am-note"><b>Model</b>: eNRTL-RK regressed to pK<sub>a</sub> and CO₂ data. <b>Predicted</b>: same model, reaction free energies and enthalpies from QM + MD (no CO₂ data used). Predictions are preliminary. Tap a point or line for its value.</p>`;
    const cv = el.querySelector('canvas');
    { const box = el.querySelector('.am-concs'), lab = box.querySelector('input:checked').closest('label'); box.scrollLeft = lab.offsetLeft - box.offsetLeft - 8; }   // phone: chosen concentration in view
    const side = () => {
      const g = G[gi], temps = tempsOf(g);
      if (!tOn) tOn = new Set(temps);
      el.querySelector('.am-ptitle').innerHTML = `${esc(a.id)} · ${+g.m.toFixed(2)} mol/kg (${g.wt} wt %)`;
      el.querySelector('.am-temps').innerHTML = temps.map((t, i) => `<button class="am-chip" data-t="${t}" aria-pressed="${tOn.has(t)}"><i style="background:${tColor(i)}"></i>${t} °C</button>`).join('');
      const used = new Set(g.exp.map((e) => e[3] || 0));
      el.querySelector('.am-srcs').innerHTML = SRC.map((s, i) => used.has(i) ? `<label class="am-src"><input type="checkbox" data-s="${i}" ${sOn.has(i) ? 'checked' : ''}>${shapeSVG(i, i >= SHAPES.length)}<span>${esc(s.label)}</span></label>` : '').join('');
      el.querySelectorAll('[data-t]').forEach((b) => b.onclick = () => { const t = +b.dataset.t; if (tOn.has(t)) tOn.delete(t); else tOn.add(t); b.setAttribute('aria-pressed', tOn.has(t)); plot(); });
      el.querySelectorAll('[data-s]').forEach((c) => c.onchange = () => { const i = +c.dataset.s; if (c.checked) sOn.add(i); else sOn.delete(i); plot(); });
    };
    const plot = () => {
      const g = G[gi], temps = tempsOf(g), ds = [], hasCurve = Object.keys(g.curves).length > 0;
      temps.forEach((t, ti) => {
        if (!tOn.has(t)) return;
        const col = tColor(ti), key = Object.keys(g.curves).find((k) => +k === t);
        if (on.exp) SRC.forEach((s, si) => {
          if (!sOn.has(si)) return;
          const pts = g.exp.filter((e) => e[0] === t && (e[3] || 0) === si).map((e) => ({ x: e[1], y: e[2] }));
          const hol = si >= SHAPES.length;
          if (pts.length) ds.push({ type: 'scatter', label: `${s.label}, ${t} °C`, data: pts, pointStyle: SHAPES[si % SHAPES.length], backgroundColor: hol ? '#FFFFFF' : col,
            borderColor: hol ? col : th.edge, borderWidth: hol ? 2 : 1, pointRadius: 5.5, pointHoverRadius: 8 });
        });
        ['model', 'pred'].forEach((k) => {
          if (!on[k]) return;
          const lab = `${k === 'model' ? 'Model' : 'Predicted'}, ${t} °C`;
          if (key && g.curves[key][k].length) ds.push({ type: 'line', label: lab, data: g.curves[key][k].map(([x, y]) => ({ x, y })), borderColor: col, borderWidth: 2.2, borderDash: k === 'model' ? [6, 4] : [], pointRadius: 0, pointHitRadius: 6, tension: 0.25 });
          else if (!hasCurve || !key) { const pts = g[k].filter((e) => e[0] === t).map((e) => ({ x: e[1], y: e[2] })); if (pts.length) ds.push({ type: 'scatter', label: lab, data: pts, pointStyle: k === 'model' ? 'dash' : 'line', borderColor: col, borderWidth: 2.5, pointRadius: 7 }); }
        });
      });
      const ex = g.exp.map((e) => e[2]).filter((x) => x > 0), xs = g.exp.map((e) => e[1]);
      const yMin = ex.length ? 10 ** (Math.floor(Math.log10(Math.min(...ex))) - 1) : 1e-3, yMax = ex.length ? 10 ** (Math.ceil(Math.log10(Math.max(...ex))) + 1) : 1e4;
      const xMax = xs.length ? Math.min(1.6, Math.ceil(Math.max(...xs) * 1.08 * 10) / 10) : 1;
      const ax = (title) => ({ title: { display: true, text: title, color: th.fg, font: { size: 13, weight: 'bold', family: th.font } }, ticks: { color: th.fg, font: { family: th.font } }, grid: { color: th.grid } });
      if (chart) chart.destroy();
      chart = new Chart(cv, { data: { datasets: ds }, options: {
        responsive: true, maintainAspectRatio: false, animation: false, parsing: false,
        interaction: { mode: 'nearest', intersect: false }, events: ['mousemove', 'mouseout', 'click', 'touchstart', 'touchmove'],
        plugins: { legend: { display: false }, tooltip: { callbacks: { label: (c) => `${c.dataset.label}: α ${c.parsed.x.toFixed(3)}, P ${c.parsed.y.toPrecision(3)} kPa` } } },
        scales: { x: Object.assign({ type: 'linear', min: 0, max: xMax }, ax('CO₂ loading (mol CO₂ / mol amine)')),
          y: Object.assign({ type: 'logarithmic', min: yMin, max: yMax }, ax('CO₂ partial pressure (kPa)'), { ticks: { color: th.fg, font: { family: th.font }, callback: (val) => { const l = Math.log10(val); return Math.abs(l - Math.round(l)) < 1e-9 ? (val >= 1e-2 && val <= 1e3 ? +val.toPrecision(1) : `1e${Math.round(l)}`) : ''; } } }) },
      } });
    };
    el.querySelectorAll('[name^="am-conc"]').forEach((r) => r.onchange = () => { gi = +r.value; tOn = null; side(); plot(); });
    el.querySelectorAll('[data-k]').forEach((c) => c.onchange = () => { on[c.dataset.k] = c.checked; plot(); });
    el.querySelectorAll('[data-all]').forEach((b) => b.onclick = () => { tOn = b.dataset.all === '1' ? new Set(tempsOf(G[gi])) : new Set(); side(); plot(); });
    side(); plot();
  }

  const facts = (a) => [['IUPAC', esc(a.iupac)], ['Formula', sub(a.formula)], ['M', `${a.mw.toFixed(2)} g/mol`], ...(a.cas ? [['CAS', esc(a.cas)]] : []),
    ['PubChem', `<a href="https://pubchem.ncbi.nlm.nih.gov/compound/${a.cid}" target="_blank" rel="noopener">CID ${a.cid}</a>`], ['SMILES', `<code>${esc(a.smiles)}</code>`], ['pK<sub>a</sub> 25 °C', a.pka25.toFixed(2)]];
  return { load, svg, confPanel, co2Panel, facts, esc, sub, SPECIES, CLASSES, tColor, store };
})();
